function hash(s){ let h = 2166136261; for(let i = 0; i < s.length; i++){ h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
function pick(arr){ return arr[Math.floor(Math.random()*arr.length)]; }
function shuffle(a){ a = a.slice(); for(let i = a.length - 1; i > 0; i--){ const j = Math.floor(Math.random()*(i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }
function esc(s){ return String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])); }

export function run(action, api){
  const S = get(), td = today();
  const close = { label: 'Закрити', fn: () => api.hide() };
  switch(action){
    case 'oracle': {
      const text = PROPHECIES[hash(td + (api.hero.name || '')) % PROPHECIES.length];
      let bonus = '';
      if(S.last.oracle !== td){ S.last.oracle = td; addSparks(1); commit(); api.refresh(); bonus = '<p class="gm-note">✦ +1 іскра мудрості за візит.</p>'; }
      api.sheet({ title: 'Оракул', html: '<p class="gm-quote">«' + esc(text) + '»</p><p>Піфія дивиться крізь дим і промовляє. Передбачення змінюється щодня.</p>' + bonus, buttons: [{ label: 'Дякую, Піфіє', fn: () => api.hide() }] });
      break;
    }
    case 'mimir': {
      if(S.last.mimir === td){
        api.sheet({ title: 'Джерело Мімира', html: '<p>Сьогодні ви вже пили з джерела. Вода мудрості дає себе лише раз на день — повертайтеся завтра.</p>', buttons: [close] });
      } else {
        api.sheet({ title: 'Джерело Мімира', html: '<p>Темна вода світиться знизу. Ворон на балці мовчки дивиться на вас. Випити — і взяти одну краплю мудрості?</p>', buttons: [
          { label: 'Випити води', primary: true, fn: () => { S.last.mimir = td; addSparks(2); commit(); api.refresh(); api.sheet({ title: 'Джерело Мімира', html: '<p class="gm-quote">«' + esc(pick(WISDOM)) + '»</p><p class="gm-note">✦ +2 іскри мудрості.</p>', buttons: [close] }); } },
          { label: 'Не зараз', fn: () => api.hide() }] });
      }
      break;
    }
    case 'sphinx': {
      const askRiddle = () => {
        const r = pick(RIDDLES), opts = shuffle([r.a].concat(r.w));
        const left = Math.max(0, 3 - (S.solved[td] || 0));
        api.sheet({ title: 'Сфінкс', html: '<p class="gm-quote">«' + esc(r.q) + '»</p><p class="gm-note">' + (left ? 'Нагорода за відгадки сьогодні: ще ' + left + '.' : 'Нагороди за сьогодні вже зібрано — можна грати для задоволення.') + '</p>', buttons: opts.map(o => ({ label: o, fn: () => {
          if(o === r.a){
            let msg = 'Вірно! Сфінкс киває кам\'яною головою.';
            if(left){ S.solved[td] = (S.solved[td] || 0) + 1; addSparks(1); commit(); api.refresh(); msg += ' <span class="gm-note">✦ +1 іскра.</span>'; }
            api.sheet({ title: 'Сфінкс', html: '<p>' + msg + '</p>', buttons: [{ label: 'Ще загадку', primary: true, fn: askRiddle }, close] });
          } else api.sheet({ title: 'Сфінкс', html: '<p>Не вгадали. Правильна відповідь — «' + esc(r.a) + '». Сфінкс терпляче чекає на нову спробу.</p>', buttons: [{ label: 'Ще загадку', primary: true, fn: askRiddle }, close] });
        } })).concat([{ label: 'Піти', fn: () => api.hide(), ghost: true }]) });
      };
      askRiddle();
      break;
    }
    case 'runes': {
      const cur = S.rune && S.rune.date === td ? RUNES.find(r => r.id === S.rune.id) : null;
      if(cur){
        api.sheet({ title: 'Коло Рун', html: '<p class="gm-rune">' + cur.r + '</p><p>Сьогодні вас благословила руна <b>' + cur.n + '</b>: «' + cur.b + '» — ' + cur.t + '.</p><p class="gm-note">Ефект благословення проявиться в боях (наступні етапи). Нова руна — завтра.</p>', buttons: [close] });
      } else {
        const three = shuffle(RUNES).slice(0, 3);
        api.sheet({ title: 'Коло Рун', html: '<p>Камені тихо світяться. Оберіть одну з трьох рун — вона благословить вас до кінця дня.</p>', buttons: three.map(r => ({ label: r.r + '  ' + r.n + ' · ' + r.b, fn: () => { S.rune = { date: td, id: r.id }; commit(); api.refresh(); api.sheet({ title: 'Коло Рун', html: '<p class="gm-rune">' + r.r + '</p><p>Руна <b>' + r.n + '</b> прийняла вас: «' + r.b + '» — ' + r.t + '.</p><p class="gm-note">Ефект проявиться в боях (наступні етапи).</p>', buttons: [close] }); } })).concat([{ label: 'Піти', fn: () => api.hide(), ghost: true }]) });
      }
      break;
    }
    case 'worldtree': {
      const bars = (api.hero.stats || []).map(s => '<div class="gm-bar-row"><span>' + esc(s.label) + '</span><div class="gm-bar-track"><i style="width:' + Math.min(100, Math.round(s.value/Math.max(20, ...api.hero.stats.map(x => x.value))*100)) + '%;background:' + s.color + '"></i></div><b>' + (Math.round(s.value*100)/100) + '</b></div>').join('');
      api.sheet({ title: 'Світове Дерево', html: '<p>Його коріння сягає глибин, крона — неба. Дерево відображає ваш власний шлях:</p>' + bars + '<p class="gm-note">Це реальні показники з ваших вправ.</p>', buttons: [close] });
      break;
    }
    case 'pantheon': {
      api.sheet({ title: 'Пантеон Богів', html: '<p>Оберіть покровителя. Його воля пасуватиме вашому шляху (бонуси з\'являться в боях). Змінити вибір можна будь-коли.</p>' + (S.patron ? '<p class="gm-note">Зараз: ' + esc((PATRONS.find(p => p.id === S.patron) || {}).n || '—') + '</p>' : ''),
        buttons: PATRONS.map(p => ({ label: p.e + '  ' + p.n + ' — ' + p.st, primary: S.patron === p.id, fn: () => { S.patron = p.id; commit(); api.refresh(); api.sheet({ title: p.e + ' ' + p.n, html: '<p class="gm-note">' + esc(p.d) + '</p><p>' + esc(p.t) + '</p><p>Покровитель обрано. Він помітить ваші старання.</p>', buttons: [{ label: 'Обрати іншого', fn: () => run('pantheon', api) }, close] }); } })).concat([{ label: 'Піти', fn: () => api.hide(), ghost: true }]) });
      break;
    }
    case 'dragon': {
      api.sheet({ title: 'Лимонний Дракон', html: '<p>' + esc(DRAGON) + '</p>', buttons: [close] });
      break;
    }
    default: return false;
  }
  return true;
}
